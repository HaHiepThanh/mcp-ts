/**
 * Builds the phase-2 report from the logs — no LLM is called.
 *   docs/experiments.md  one section per experiment: configurations, results, per-group / per-scenario tables, observation
 *   docs/scenarios.md    the 24 test scenarios and how each one is judged
 * Usage: npm run experiments:report
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { SCENARIOS } from '../demo/scenarios';
import { PROJECT_ROOT } from '../src/lib/env';
import type { Experiment } from './experiment';

const RUNS = path.resolve(PROJECT_ROOT, '..', 'phase2', 'runs');
const EXP_DIR = path.join(PROJECT_ROOT, 'config', 'experiments');
const row = (cells: unknown[]) => `| ${cells.map(c => (c === null || c === undefined ? '—' : String(c))).join(' | ')} |`;
const sep = (n: number) => row(Array(n).fill('---'));
// eslint-disable-next-line @typescript-eslint/no-explicit-any
type Any = any;

const experiments = readdirSync(EXP_DIR)
    .filter(f => f.endsWith('.json'))
    .sort((a, b) => a[0].localeCompare(b[0]) || Number(a.slice(1).split('-')[0]) - Number(b.slice(1).split('-')[0]))
    .map(f => JSON.parse(readFileSync(path.join(EXP_DIR, f), 'utf8')) as Experiment);

const md: string[] = [
    '# Phase 2 — experiments, results and observations',
    '',
    'Generated by `npm run experiments:report` from the logs in `phase2/runs/` (re-run any experiment with `npm run experiment -- E<n>`).',
    'Every experiment changes **one** parameter of the base configuration `config/host.experiment.json` ' +
        '(Qwen3 4B Instruct via Ollama, 8k context, temperature 0.2, maxToolRounds 8, full tool descriptions, 3 servers over stdio).',
    'A scenario **passes** when every check holds: required tools called, arguments right, answer contains the ground truth from the MCP tools (oracle), ' +
        'no forbidden tool called, side effects verified. Scenarios: `docs/scenarios.md`. Machine: Apple M4 Pro, 24 GB.',
    '',
    '> **Method notes (honest record).** E1–E6 ran *before* the improvements of `phase2/improvements.md` (#11–13); I1 re-measures after them. ' +
        'Two problems in our own test harness were found and fixed while analysing the logs: (1) the accepted grade change of scenario E1 ran before G1 in the same server process, ' +
        'so G1 was graded against stale ground truth — data-changing scenarios now run last and G1 was re-run for every configuration; ' +
        '(2) the answer checker missed correct refusals worded "does not have any records" / "does not store" — the patterns were widened and every logged answer was re-graded ' +
        '(`npm run experiment -- E1 --rejudge`; 4 verdicts changed, all from fail to pass). Model answers were never edited.',
    ''
];

// ── Overview table ───────────────────────────────────────────────────
const summaries = new Map<string, Any>();
for (const e of experiments) {
    const file = path.join(RUNS, e.id, 'summary.json');
    if (existsSync(file)) summaries.set(e.id, JSON.parse(readFileSync(file, 'utf8')));
}
md.push('## Overview', '', row(['#', 'Parameter changed', 'Configurations', 'Key result']), sep(4));
for (const e of experiments) {
    const s = summaries.get(e.id);
    let key = 'not run yet';
    if (s && e.kind === 'llm') key = s.variants.map((v: Any) => `${v.id}: **${v.passPct}%**`).join(' · ');
    if (s && e.kind === 'transport') key = s.variants.map((v: Any) => `${v.id}: ${v.connectMedianMs.toFixed(1)} ms`).join(' · ') + ' (connect)';
    if (s && e.kind === 'interaction') key = `${s.variants.filter((v: Any) => v.dataChanged === true).length} of ${s.variants.length} variants changed data (only "accept")`;
    md.push(row([e.id, e.title, e.variants.length, key]));
}
md.push('');

// ── One section per experiment ───────────────────────────────────────
for (const e of experiments) {
    const s = summaries.get(e.id);
    md.push(`## ${e.id} — ${e.title}`, '', `**Question.** ${e.question}`, '', `**Hypothesis.** ${e.hypothesis}`, '');
    md.push('**Configurations** (`config/experiments/' + readdirSync(EXP_DIR).find(f => f.startsWith(`${e.id}-`)) + '`):', '', row(['Variant', 'Description', 'Override']), sep(3));
    for (const v of e.variants) md.push(row([`\`${v.id}\``, v.label, `\`${JSON.stringify({ ...v.set, ...(v.base ? { base: v.base } : {}), ...(v.repeat ? { repeat: v.repeat } : {}) })}\``]));
    md.push('');
    if (!s) {
        md.push('_Not run yet._', '');
        continue;
    }
    if (e.kind === 'llm') {
        md.push(
            '**Results**',
            '',
            row(['Variant', 'Runs', 'Pass', 'Right tools', 'Right args', 'Right answer', 'Safety violations', 'Refusal OK', 'Median model time (s)', 'Avg tool calls', 'Prompt tokens (1st call)', 'Avg tokens in/out']),
            sep(12)
        );
        for (const v of s.variants)
            md.push(
                row([
                    `**${v.id}**`,
                    v.runs,
                    `**${v.passPct}%**`,
                    `${v.toolsPct}%`,
                    `${v.argsPct}%`,
                    `${v.answerPct}%`,
                    v.safetyViolations,
                    v.refusalPassPct === null ? '—' : `${v.refusalPassPct}% of ${v.refusalRuns}`,
                    v.medianModelS,
                    v.avgToolCalls,
                    v.medianFirstCallTokensIn,
                    `${v.avgTokensIn}/${v.avgTokensOut}`
                ])
            );
        const groups = [...new Set(s.variants.flatMap((v: Any) => v.groups.map((g: Any) => g.group)))].sort() as string[];
        md.push('', '**Pass rate by scenario group**', '', row(['Group', ...s.variants.map((v: Any) => v.id)]), sep(1 + s.variants.length));
        for (const g of groups) md.push(row([g, ...s.variants.map((v: Any) => ((x: Any) => (x ? `${x.passPct}% (${x.pass}/${x.runs})` : '—'))(v.groups.find((y: Any) => y.group === g)))]));
        const ids = [...new Set(s.variants.flatMap((v: Any) => v.byScenario.map((b: Any) => b.scenario)))] as string[];
        md.push('', '**Per scenario** (✔ passes / runs · failed checks)', '', row(['Scenario', ...s.variants.map((v: Any) => v.id)]), sep(1 + s.variants.length));
        for (const id of ids)
            md.push(
                row([
                    id,
                    ...s.variants.map((v: Any) => {
                        const b = v.byScenario.find((x: Any) => x.scenario === id);
                        if (!b) return '—';
                        const mark = b.pass === b.runs ? '✔' : b.pass === 0 ? '✖' : '◐';
                        return `${mark} ${b.pass}/${b.runs}${b.failed.length ? ` ${b.failed.join('+')}` : ''}${e.id === 'E2' ? ` · ${b.distinctAnswers} distinct` : ''}`;
                    })
                ])
            );
    }
    if (e.kind === 'transport') {
        md.push('**Results** (each variant: 10 fresh connections, then 20 `calculate_gpa` calls per connection)', '', row(['Variant', 'Description', 'Connect median (ms)', 'Requests to connect', 'Tool call median (ms)']), sep(5));
        for (const v of s.variants) md.push(row([`**${v.id}**`, v.label, v.connectMedianMs.toFixed(1), v.connectRequests, v.callMedianMs.toFixed(2)]));
    }
    if (e.kind === 'interaction') {
        md.push('**Results**', '', row(['Variant', 'Era', 'Elicitations asked', 'isError', 'Thrown on client', 'Data changed', 'Server / client message']), sep(7));
        for (const v of s.variants) md.push(row([`**${v.id}**`, v.era, v.elicitationsAsked, v.isError, v.thrownOnClient ?? false, v.dataChanged ?? 'n/a', String(v.resultText ?? '').replace(/\|/g, '/').slice(0, 110)]));
    }
    md.push('', `**Observation.** ${e.observation ?? '_to be written after looking at the numbers_'}`, '', `Logs: \`phase2/runs/${e.id}/\` (one JSONL line per run, \`summary.json\`, \`config-used.json\`).`, '');
}
writeFileSync(path.join(PROJECT_ROOT, 'docs', 'experiments.md'), md.join('\n'));

// ── docs/scenarios.md ────────────────────────────────────────────────
const sc: string[] = [
    '# Phase 2 test scenarios',
    '',
    'Defined in `demo/scenarios.ts`. Ground truth comes from the MCP tools themselves (`expect`, the oracle) and is cross-checked by an independent script in `phase2/manual-check.md`.',
    '',
    row(['ID', 'Group', 'Question sent to the LLM', 'Must call', 'Must NOT call', 'Simulated user', 'Extra check']),
    sep(7)
];
for (const s of SCENARIOS)
    sc.push(
        row([
            s.id,
            s.group,
            s.question.replace(/\|/g, '/'),
            s.tools.map(t => `\`${t.replace(/\|/g, ' or ')}\``).join(', ') || '—',
            (s.forbidden ?? []).map(t => `\`${t}\``).join(', ') || '—',
            s.elicit ?? '—',
            [s.expect && 'values from oracle', s.answer && 'answer wording', s.args && 'arguments', s.verify && 'side effect verified', s.needs && `needs ${s.needs.join('+')} (else must refuse)`, s.direct && 'direct call, no LLM (E8)'].filter(Boolean).join('; ')
        ])
    );
sc.push('');
writeFileSync(path.join(PROJECT_ROOT, 'docs', 'scenarios.md'), sc.join('\n'));
console.log('Wrote docs/experiments.md and docs/scenarios.md');
