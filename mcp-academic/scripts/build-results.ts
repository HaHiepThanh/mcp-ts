/**
 * Collects the numbers the slides need into docs/results.md:
 * outputs/examples/*.json (from `npm run examples`) and outputs/logs/chat-*.jsonl (from `npm run chat`).
 * Run: npm run results
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { PROJECT_ROOT } from '../src/lib/env';

const EX = path.join(PROJECT_ROOT, 'outputs', 'examples');
const LOGS = path.join(PROJECT_ROOT, 'outputs', 'logs');

type Json = Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any
const load = (name: string): Json | undefined => (existsSync(path.join(EX, `${name}.json`)) ? JSON.parse(readFileSync(path.join(EX, `${name}.json`), 'utf8')) : undefined);
const table = (headers: string[], rows: unknown[][]) =>
    [`| ${headers.join(' | ')} |`, `| ${headers.map(() => '---').join(' | ')} |`, ...rows.map(r => `| ${r.map(c => String(c ?? '').replace(/\|/g, '\\|')).join(' | ')} |`)].join('\n');

const out: string[] = [
    '# Results',
    '',
    `Generated by \`npm run results\` on ${new Date().toISOString().slice(0, 16).replace('T', ' ')} UTC from \`outputs/examples/*.json\` and \`outputs/logs/chat-*.jsonl\`. Timings come from one machine (Apple M4 Pro) and vary between runs.`,
    ''
];

// ── Examples ─────────────────────────────────────────────────────────
const summary = load('summary');
if (summary) {
    out.push('## 1. Example suite', '', table(['Group', 'Example', 'Passed', 'Seconds'], summary.summary.map((s: Json) => [s.group, s.example, s.ok ? '✅' : '❌', s.seconds])), '');
}

const s2 = load('s2-register-tool');
if (s2) {
    out.push(
        '## 2. Tool calls with different parameter sets (S2)',
        '',
        table(
            ['Case', 'Arguments', 'isError', 'Result (short)'],
            s2.steps
                .filter((s: Json) => s.method === 'callTool')
                .map((s: Json) => [s.step, JSON.stringify(s.params?.arguments ?? {}), s.result?.isError ?? s.result?.isError === true, (s.result?.text ?? JSON.stringify(s.result?.structuredContent ?? s.result?.content ?? '')).slice(0, 90)])
        ),
        ''
    );
}

const s8 = load('s8-transports');
if (s8?.comparison) {
    out.push(
        '## 3. Transports × protocol eras (S8)',
        '',
        table(['Transport', 'Negotiation', 'Era', 'Connect (ms)', 'First call (ms)', 'Avg of 20 calls (ms)'], s8.comparison.map((r: Json) => [r.transport, r.negotiation, r.era, r.connectMs, r.firstCallMs, r.avgOf20CallsMs])),
        '',
        'Security checks on the HTTP endpoint:',
        '',
        table(['Request', 'Status'], s8.steps.filter((s: Json) => s.method.startsWith('POST')).map((s: Json) => [s.step, s.result?.status])),
        ''
    );
}

const c1 = load('c1-client-connect');
if (c1) {
    out.push(
        '## 4. Connecting (C1)',
        '',
        table(
            ['Client option', 'Era', 'Requests during connect', 'Outcome'],
            c1.steps.map((s: Json) => [s.step, s.result?.era ?? '', s.result?.requestsDuringConnect ? JSON.stringify(s.result.requestsDuringConnect) : '', s.ok ? 'ok' : `${s.error?.name} ${s.error?.code ?? ''}`])
        ),
        ''
    );
}

const c2 = load('c2-request-options-errors');
if (c2) {
    out.push(
        '## 5. Request options and failure taxonomy (C2)',
        '',
        table(['Options (job ≈ 1.2 s)', 'Time (ms)', 'Outcome'], c2.steps.slice(0, 4).map((s: Json) => [s.step, s.ms, s.ok ? `completed, ${s.result.progressUpdates} progress updates` : `${s.error.code}: ${s.error.message}`])),
        '',
        table(['Failure', 'Surfaces as'], c2.taxonomy.map((t: Json) => [t.failure, t.surfacesAs])),
        ''
    );
}

const c4 = load('c4-caching');
if (c4) {
    out.push('## 6. Response cache (C4)', '', table(['Scenario', 'Era', 'Calls', 'Requests reaching the server'], c4.summary.map((r: Json) => [r.scenario, r.era, r.calls, r.requestsReachingServer])), '');
}

const s7 = load('s7-elicitation-sampling');
if (s7) {
    out.push(
        '## 7. Elicitation answers (S7)',
        '',
        table(['Case', 'Tool result'], s7.steps.filter((s: Json) => s.step.startsWith('update_grade')).map((s: Json) => [s.step, s.result?.text ?? s.error?.message])),
        ''
    );
}

// ── Chat logs ────────────────────────────────────────────────────────
const logFiles = existsSync(LOGS) ? readdirSync(LOGS).filter(f => /^chat-.*\.jsonl$/.test(f)).sort() : [];
const turns: Json[] = logFiles.flatMap(f =>
    readFileSync(path.join(LOGS, f), 'utf8')
        .split('\n')
        .filter(Boolean)
        .map(l => JSON.parse(l))
);
const recent = turns.filter(t => t.llmCalls).slice(-12);
if (recent.length) {
    const llmMs = (t: Json) => t.llmCalls.reduce((a: number, c: Json) => a + c.ms, 0);
    const toolMs = (t: Json) => t.toolCalls.reduce((a: number, c: Json) => a + c.ms, 0);
    out.push(
        '## 8. Chat host with Gemini — latest turns',
        '',
        table(
            ['Question', 'Model', 'Tools called', 'Rounds', 'Total (s)', 'LLM (s)', 'MCP tools (ms)', 'Tokens in/out'],
            recent.map(t => [
                t.question.slice(0, 70),
                t.model,
                t.toolCalls.map((c: Json) => `${c.server}.${c.tool}${c.isError ? ' ✖' : ''}`).join(', ') || '—',
                t.rounds,
                (t.totalMs / 1000).toFixed(1),
                (llmMs(t) / 1000).toFixed(1),
                toolMs(t),
                `${t.usage.inputTokens}/${t.usage.outputTokens}`
            ])
        ),
        ''
    );
    // Tool time of sampling/elicitation turns includes nested LLM calls and human thinking time,
    // so the split is computed on "clean" turns only.
    const clean = recent.filter(t => t.samplingCalls === 0 && t.elicitations.length === 0);
    const total = clean.reduce((a, t) => a + t.totalMs, 0);
    const llm = clean.reduce((a, t) => a + llmMs(t), 0);
    const tools = clean.reduce((a, t) => a + toolMs(t), 0);
    if (total > 0) {
        out.push(
            `Time split over the ${clean.length} turns without sampling or user confirmation: LLM requests **${((llm / total) * 100).toFixed(1)}%**, ` +
                `MCP tool calls **${((tools / total) * 100).toFixed(2)}%**, host overhead **${(((total - llm - tools) / total) * 100).toFixed(1)}%**.`,
            '',
            'In turns with sampling, the tool time contains the nested LLM request; in turns with elicitation it contains the time the user took to answer.',
            ''
        );
    }
}

writeFileSync(path.join(PROJECT_ROOT, 'docs', 'results.md'), out.join('\n'));
console.log(`docs/results.md written (${out.length} lines, ${turns.length} chat turns available)`);
